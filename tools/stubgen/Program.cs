// Stub generator: reads Unity module DLL metadata via Roslyn and emits compilable C# "throw null" stubs
// (public/protected surface only). Types listed in the config can be skipped entirely ("-Type") or
// have named members skipped ("Type: a, b") so a hand-written partial can provide them.
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

static class Program
{
    static HashSet<string> excludedTypes = new();
    static Dictionary<string, HashSet<string>> skipMembers = new();
    static HashSet<string> noCtor = new();
    static HashSet<string> forceInclude = new();
    static HashSet<string> noopTypes = new();
    static bool allInternalEnv = Environment.GetEnvironmentVariable("STUB_ALL_INTERNAL") == "1";
    static bool AllInt(ISymbol s) => allInternalEnv && (s.ContainingAssembly?.Name.StartsWith("UnityEngine.") ?? false) && s.ContainingAssembly.Name != "UnityEngine.UIElementsModule";
    static HashSet<INamedTypeSymbol> emitted = new(SymbolEqualityComparer.Default);
    static HashSet<IAssemblySymbol> unityAsm = new(SymbolEqualityComparer.Default);

    static readonly SymbolDisplayFormat TF = new(
        globalNamespaceStyle: SymbolDisplayGlobalNamespaceStyle.Included,
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameAndContainingTypesAndNamespaces,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes | SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

    static int Main(string[] args)
    {
        // args: outDir config refDir... -- moduleDlls...
        string outDir = args[0], config = args[1];
        var refs = new List<string>(); var mods = new List<string>();
        bool m = false;
        foreach (var a in args.Skip(2)) { if (a == "--") { m = true; continue; } (m ? mods : refs).Add(a); }
        foreach (var raw in File.ReadAllLines(config))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line.StartsWith("#")) continue;
            if (line.StartsWith("-")) { excludedTypes.Add(line[1..].Trim()); continue; }
            if (line.StartsWith("~")) { noopTypes.Add(line[1..].Trim()); continue; }
            if (line.StartsWith("+")) { forceInclude.Add(line[1..].Trim()); continue; }
            if (line.StartsWith("!noctor ")) { noCtor.Add(line[8..].Trim()); continue; }
            var i = line.IndexOf(':');
            var t = line[..i].Trim();
            if (!skipMembers.TryGetValue(t, out var set)) skipMembers[t] = set = new();
            foreach (var n in line[(i + 1)..].Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)) set.Add(n);
        }
        var allRefs = refs.Concat(mods).Select(p => (MetadataReference)MetadataReference.CreateFromFile(p)).ToList();
        var comp = CSharpCompilation.Create("x", references: allRefs, options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, metadataImportOptions: MetadataImportOptions.All));
        var modAsms = new List<IAssemblySymbol>();
        foreach (var r in allRefs.Skip(refs.Count))
            if (comp.GetAssemblyOrModuleSymbol(r) is IAssemblySymbol asm) { modAsms.Add(asm); unityAsm.Add(asm); }

        // pass 1: collect emitted types
        foreach (var asm in modAsms) foreach (var t in AllTypes(asm.GlobalNamespace)) if (ShouldEmitType(t)) emitted.Add(t);
        // pass 2: emit
        Directory.CreateDirectory(outDir);
        foreach (var asm in modAsms)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> stubs from " + asm.Name + "</auto-generated>");
            sb.AppendLine("#pragma warning disable");
            foreach (var g in AllTypes(asm.GlobalNamespace).Where(t => t.ContainingType == null && emitted.Contains(t)).GroupBy(t => t.ContainingNamespace.ToDisplayString()))
            {
                bool hasNs = !string.IsNullOrEmpty(g.Key) && g.Key != "<global namespace>";
                if (hasNs) sb.AppendLine($"namespace {g.Key} {{");
                foreach (var t in g) EmitType(sb, t, 1);
                if (hasNs) sb.AppendLine("}");
            }
            File.WriteAllText(Path.Combine(outDir, asm.Name + ".g.cs"), sb.ToString());
        }
        Console.WriteLine($"emitted {emitted.Count} types");
        return 0;
    }

    static IEnumerable<INamedTypeSymbol> AllTypes(INamespaceSymbol ns)
    {
        foreach (var t in ns.GetTypeMembers()) { yield return t; foreach (var n in Nested(t)) yield return n; }
        foreach (var n in ns.GetNamespaceMembers()) foreach (var t in AllTypes(n)) yield return t;
    }
    static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol t)
    {
        foreach (var n in t.GetTypeMembers()) { yield return n; foreach (var x in Nested(n)) yield return x; }
    }

    static string FullName(INamedTypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat.WithGenericsOptions(SymbolDisplayGenericsOptions.None));

    static bool IsErrorObsolete(ISymbol s) => s.GetAttributes().Any(a => a.AttributeClass?.Name == "ObsoleteAttribute" && a.ConstructorArguments.Length >= 2 && a.ConstructorArguments[1].Value is true);

    static bool ShouldEmitType(INamedTypeSymbol t)
    {
        var ns = t.ContainingNamespace?.ToDisplayString() ?? "";
        if (ns.StartsWith("System") || ns.StartsWith("Microsoft") || ns.StartsWith("JetBrains") || ns.StartsWith("Mono") || ns.StartsWith("Bee") || ns.StartsWith("Unity.Burst") || ns.StartsWith("Unity.Collections") && false) return false;
        for (var c = t; c != null; c = c.ContainingType)
        {
            if (c.DeclaredAccessibility != Accessibility.Public && !forceInclude.Contains(FullName(c)) && !(AllInt(c) && c.DeclaredAccessibility is Accessibility.Internal)) return false;
            if (excludedTypes.Contains(FullName(c))) return false;
            if (IsErrorObsolete(c)) return false;
            if (c.Name.Contains('<')) return false;
        }
        return true;
    }

    static bool TypeOk(ITypeSymbol t)
    {
        switch (t)
        {
            case IArrayTypeSymbol a: return TypeOk(a.ElementType);
            case IPointerTypeSymbol p: return TypeOk(p.PointedAtType);
            case ITypeParameterSymbol: return true;
            case IFunctionPointerTypeSymbol: return false;
            case INamedTypeSymbol n:
                if (n.TypeKind == TypeKind.Error) return false;
                if (n.IsGenericType && !n.TypeArguments.All(TypeOk)) return false;
                var def = n.OriginalDefinition;
                if (def.ContainingAssembly != null && unityAsm.Contains(def.ContainingAssembly)) return emitted.Contains(def) || IsExcludedButProvided(def);
                // System types: only public
                return def.DeclaredAccessibility == Accessibility.Public && (def.ContainingType == null || TypeOk(def.ContainingType));
            default: return true;
        }
    }
    static bool IsExcludedButProvided(INamedTypeSymbol t)
    {
        for (var c = t; c != null; c = c.ContainingType) if (excludedTypes.Contains(FullName(c))) return c.DeclaredAccessibility == Accessibility.Public;
        return false;
    }

    static string T(ITypeSymbol t) => t.ToDisplayString(TF);

    static bool Accessible(ISymbol s) => s.DeclaredAccessibility is Accessibility.Public or Accessibility.Protected or Accessibility.ProtectedOrInternal;
    static string Acc(ISymbol s) => s.DeclaredAccessibility switch
    {
        Accessibility.Public => "public", Accessibility.Protected => "protected", Accessibility.ProtectedOrInternal => "protected internal",
        Accessibility.Internal => "internal", Accessibility.ProtectedAndInternal => "private protected", _ => "private"
    };

    static string Ind(int n) => new string(' ', n * 4);

    static void EmitType(StringBuilder sb, INamedTypeSymbol t, int ind)
    {
        string I = Ind(ind);
        foreach (var a in t.GetAttributes())
        {
            var an = a.AttributeClass?.ToDisplayString();
            if (an == "System.FlagsAttribute") sb.AppendLine(I + "[global::System.Flags]");
            else if (an == "System.SerializableAttribute") sb.AppendLine(I + "[global::System.Serializable]");
            else if (an == "System.AttributeUsageAttribute")
            {
                var parts = new List<string> { $"(global::System.AttributeTargets){Convert.ToInt64(a.ConstructorArguments[0].Value)}" };
                foreach (var na in a.NamedArguments) parts.Add($"{na.Key} = {(na.Value.Value is bool b ? (b ? "true" : "false") : na.Value.Value)}");
                sb.AppendLine(I + $"[global::System.AttributeUsage({string.Join(", ", parts)})]");
            }
        }
        if (t.IsSerializable && !t.GetAttributes().Any(a => a.AttributeClass?.Name == "SerializableAttribute") && t.TypeKind != TypeKind.Enum && t.TypeKind != TypeKind.Delegate)
            sb.AppendLine(I + "[global::System.Serializable]");
        string name = t.Name.Contains('@') ? t.Name : SyntaxFacts.GetKeywordKind(t.Name) != SyntaxKind.None ? "@" + t.Name : t.Name;
        string tps = t.TypeParameters.Length > 0 ? "<" + string.Join(", ", t.TypeParameters.Select(p => (p.Variance == VarianceKind.Out ? "out " : p.Variance == VarianceKind.In ? "in " : "") + p.Name)) + ">" : "";
        string cons = Constraints(t.TypeParameters);

        if (t.TypeKind == TypeKind.Enum)
        {
            sb.AppendLine($"{I}{(t.DeclaredAccessibility == Accessibility.Public ? "public" : "internal")} enum {name} : {T(t.EnumUnderlyingType)} {{");
            foreach (var f in t.GetMembers().OfType<IFieldSymbol>().Where(f => f.HasConstantValue))
                sb.AppendLine($"{I}    {Esc(f.Name)} = unchecked(({T(t.EnumUnderlyingType)}){Convert.ToString(f.ConstantValue, System.Globalization.CultureInfo.InvariantCulture)}),");
            sb.AppendLine(I + "}");
            return;
        }
        if (t.TypeKind == TypeKind.Delegate)
        {
            var inv = t.DelegateInvokeMethod;
            if (!TypeOk(inv.ReturnType) || inv.Parameters.Any(p => !TypeOk(p.Type))) { sb.AppendLine($"{I}{(t.DeclaredAccessibility == Accessibility.Public ? "public" : "internal")} delegate void {name}{tps}();"); return; }
            sb.AppendLine($"{I}{(t.DeclaredAccessibility == Accessibility.Public ? "public" : "internal")} unsafe delegate {RetT(inv)} {name}{tps}({Params(inv.Parameters)}){cons};");
            return;
        }

        string kind = t.TypeKind switch { TypeKind.Interface => "interface", TypeKind.Struct => "struct", _ => "class" };
        string mods = t.DeclaredAccessibility == Accessibility.Public ? "public " : "internal ";
        if (t.TypeKind == TypeKind.Class)
        {
            if (t.IsStatic) mods += "static ";
            else if (t.IsAbstract) mods += "abstract ";
            else if (t.IsSealed) mods += "sealed ";
        }
        if (t.TypeKind == TypeKind.Struct && t.IsReadOnly) mods += "readonly ";
        var bases = new List<string>();
        if (t.TypeKind == TypeKind.Class && t.BaseType != null && t.BaseType.SpecialType != SpecialType.System_Object && TypeOk(t.BaseType)) bases.Add(T(t.BaseType));
        foreach (var it in t.Interfaces) if (TypeOk(it) && Accessible2(it)) bases.Add(T(it));
        sb.AppendLine($"{I}{mods}unsafe {(t.IsRefLikeType ? "ref " : "")}partial {kind} {name}{tps}{(bases.Count > 0 ? " : " + string.Join(", ", bases) : "")}{cons} {{");

        var full = FullName(t);
        skipMembers.TryGetValue(full, out var skip);
        bool isIface = t.TypeKind == TypeKind.Interface;
        bool forced = forceInclude.Contains(full) || AllInt(t);
        string MI = Ind(ind + 1);
        bool hasParamless = false;

        foreach (var mem in t.GetMembers())
        {
            if (skip != null && (skip.Contains(mem.Name) || skip.Contains("*"))) continue;
            if (mem.IsImplicitlyDeclared) continue;
            if (IsErrorObsolete(mem)) continue;
            bool explicitImpl = mem is IMethodSymbol { MethodKind: MethodKind.ExplicitInterfaceImplementation } || mem is IPropertySymbol { ExplicitInterfaceImplementations.Length: > 0 } || mem is IEventSymbol { ExplicitInterfaceImplementations.Length: > 0 };
            if (explicitImpl) continue; // handled below
            if (!isIface && !Accessible(mem) && !(forced && mem.DeclaredAccessibility is Accessibility.Internal or Accessibility.ProtectedOrInternal or Accessibility.ProtectedAndInternal)) continue;
            if (mem.Name.Contains('<')) continue;
            try
            {
                switch (mem)
                {
                    case IFieldSymbol f:
                        if (!TypeOk(f.Type) || f.IsFixedSizeBuffer) break;
                        if (f.IsConst) sb.AppendLine($"{MI}{Acc(f)} const {T(f.Type)} {Esc(f.Name)} = {Lit(f.ConstantValue, f.Type)};");
                        else sb.AppendLine($"{MI}{Acc(f)} {(f.IsStatic ? "static " : "")}{(f.IsReadOnly ? "readonly " : "")}{T(f.Type)} {Esc(f.Name)};");
                        break;
                    case IPropertySymbol p:
                        if (!TypeOk(p.Type) || p.Parameters.Any(x => !TypeOk(x.Type))) { if (p.IsAbstract) Console.Error.WriteLine("WARN abstract skipped " + p); break; }
                        EmitProperty(sb, MI, p, isIface, null);
                        break;
                    case IEventSymbol e:
                        if (!TypeOk(e.Type)) break;
                        if (isIface) sb.AppendLine($"{MI}event {T(e.Type)} {Esc(e.Name)};");
                        else sb.AppendLine($"{MI}{Acc(e)} {Mods(e)}event {T(e.Type)} {Esc(e.Name)}{(e.IsAbstract ? ";" : " { add { } remove { } }")}");
                        break;
                    case IMethodSymbol mt:
                        if (mt.MethodKind is MethodKind.PropertyGet or MethodKind.PropertySet or MethodKind.EventAdd or MethodKind.EventRemove or MethodKind.StaticConstructor or MethodKind.Destructor) break;
                        if (!TypeOk(mt.ReturnType) || mt.Parameters.Any(x => !TypeOk(x.Type))) { if (mt.IsAbstract) Console.Error.WriteLine("WARN abstract skipped " + mt); break; }
                        if (mt.MethodKind == MethodKind.Constructor)
                        {
                            if (t.TypeKind == TypeKind.Struct && mt.Parameters.Length == 0) break;
                            if (mt.Parameters.Length == 0) hasParamless = true;
                            sb.AppendLine($"{MI}{Acc(mt)} {name}({Params(mt.Parameters)}) {BaseCall(t)}{{ }}");
                            break;
                        }
                        EmitMethod(sb, MI, mt, isIface, null);
                        break;
                }
            }
            catch (Exception ex) { Console.Error.WriteLine($"ERR {mem}: {ex.Message}"); }
        }
        if (t.TypeKind == TypeKind.Class && !t.IsStatic && !hasParamless && !noCtor.Contains(full))
        {
            // keep the real parameterless constructor's accessibility (members may be skipped: hand-written classes like MonoBehaviour)
            var real = t.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0 && Accessible(c));
            sb.AppendLine($"{MI}{(real != null ? Acc(real) : "internal")} {name}() {BaseCall(t)}{{ }}");
        }

        // explicit interface implementations needed
        if (!isIface)
        {
            foreach (var it in t.AllInterfaces)
            {
                if (!TypeOk(it) || !Accessible2(it)) continue;
                foreach (var im in it.GetMembers())
                {
                    if (im.IsStatic) continue;
                    var impl = t.FindImplementationForInterfaceMember(im);
                    if (impl == null || !SymbolEqualityComparer.Default.Equals(impl.ContainingType, t)) continue;
                    bool isExplicit = impl is IMethodSymbol { MethodKind: MethodKind.ExplicitInterfaceImplementation } || impl is IPropertySymbol { ExplicitInterfaceImplementations.Length: > 0 } || impl is IEventSymbol { ExplicitInterfaceImplementations.Length: > 0 };
                    if (!isExplicit && Accessible(impl) && !(skip != null && skip.Contains(impl.Name))) continue;
                    if (!isExplicit && skip != null && skip.Contains(impl.Name)) continue; // hand-written provides
                    if (!isExplicit) continue;
                    try
                    {
                        if (im is IMethodSymbol imt && imt.MethodKind == MethodKind.Ordinary)
                        {
                            if (!TypeOk(imt.ReturnType) || imt.Parameters.Any(x => !TypeOk(x.Type))) continue;
                            EmitMethod(sb, MI, imt, false, it);
                        }
                        else if (im is IPropertySymbol ip)
                        {
                            if (!TypeOk(ip.Type)) continue;
                            EmitProperty(sb, MI, ip, false, it);
                        }
                        else if (im is IEventSymbol ie)
                        {
                            if (!TypeOk(ie.Type)) continue;
                            sb.AppendLine($"{MI}event {T(ie.Type)} {T(it)}.{Esc(ie.Name)} {{ add {{ }} remove {{ }} }}");
                        }
                    }
                    catch (Exception ex) { Console.Error.WriteLine($"ERR {im}: {ex.Message}"); }
                }
            }
        }
        foreach (var nt in t.GetTypeMembers()) if (emitted.Contains(nt)) EmitType(sb, nt, ind + 1);
        sb.AppendLine(I + "}");
    }

    static bool IsNoop(INamedTypeSymbol t) { for (var c = t; c != null; c = c.ContainingType) if (noopTypes.Contains(FullName(c))) return true; return false; }
    static bool Accessible2(INamedTypeSymbol t) => unityAsm.Contains(t.ContainingAssembly) || t.DeclaredAccessibility == Accessibility.Public;

    static string BaseCall(INamedTypeSymbol t)
    {
        if (t.TypeKind != TypeKind.Class || t.BaseType == null) return "";
        var b = t.BaseType.OriginalDefinition;
        if (!unityAsm.Contains(b.ContainingAssembly)) return "";
        return "";
    }

    static string Mods(ISymbol s)
    {
        var sb = new StringBuilder();
        if (s.IsStatic) sb.Append("static ");
        if (s.IsAbstract) sb.Append("abstract ");
        else if (s.IsOverride)
        {
            var ov = s switch { IMethodSymbol m => (ISymbol)m.OverriddenMethod, IPropertySymbol p => p.OverriddenProperty, IEventSymbol e => e.OverriddenEvent, _ => null };
            if (ov != null && OverrideTargetEmitted(ov)) sb.Append(s.IsSealed ? "sealed override " : "override ");
            else if (!s.ContainingType.IsSealed && !s.IsSealed) sb.Append("virtual ");
        }
        else if (s.IsVirtual && !s.ContainingType.IsSealed) sb.Append("virtual ");
        return sb.ToString();
    }

    static bool OverrideTargetEmitted(ISymbol ov)
    {
        var ct = ov.ContainingType.OriginalDefinition;
        if (!unityAsm.Contains(ct.ContainingAssembly)) return true;
        if (!emitted.Contains(ct)) return IsExcludedButProvided(ct);
        if (!Accessible(ov) && !(AllInt(ov) && ov.DeclaredAccessibility is Accessibility.Internal or Accessibility.ProtectedOrInternal or Accessibility.ProtectedAndInternal)) return false;
        if (skipMembers.TryGetValue(FullName(ct), out var sk) && sk.Contains(ov.Name)) return true; // hand-written must provide virtual
        if (ov is IMethodSymbol m && (!TypeOk(m.ReturnType) || m.Parameters.Any(x => !TypeOk(x.Type)))) return false;
        if (ov is IPropertySymbol p && !TypeOk(p.Type)) return false;
        return true;
    }

    static void EmitProperty(StringBuilder sb, string MI, IPropertySymbol p, bool isIface, INamedTypeSymbol explicitOf)
    {
        string nm = p.IsIndexer ? $"this[{Params(p.Parameters)}]" : Esc(p.Name);
        string rt = (p.ReturnsByRef ? "ref " : p.ReturnsByRefReadonly ? "ref readonly " : "") + T(p.Type);
        if (isIface)
        {
            sb.AppendLine($"{MI}{rt} {nm} {{ {(p.GetMethod != null ? "get; " : "")}{(p.SetMethod != null ? "set; " : "")}}}");
            return;
        }
        if (explicitOf != null)
        {
            nm = p.IsIndexer ? $"{T(explicitOf)}.this[{Params(p.Parameters)}]" : $"{T(explicitOf)}.{Esc(p.Name)}";
            sb.AppendLine($"{MI}{rt} {nm} {{ {(p.GetMethod != null ? "get => throw null; " : "")}{(p.SetMethod != null ? "set => throw null; " : "")}}}");
            return;
        }
        var acc = p.DeclaredAccessibility;
        string Acc2(IMethodSymbol m) => m.DeclaredAccessibility == acc ? "" : Acc(m) + " ";
        bool frc = AllInt(p) || forceInclude.Contains(FullName(p.ContainingType));
        bool AccOk(IMethodSymbol m) => Accessible(m) || frc && m.DeclaredAccessibility is Accessibility.Internal or Accessibility.ProtectedAndInternal or Accessibility.ProtectedOrInternal;
        bool getOk = p.GetMethod != null && AccOk(p.GetMethod);
        bool setOk = p.SetMethod != null && AccOk(p.SetMethod);
        if (p.IsOverride) { getOk = p.GetMethod != null; setOk = p.SetMethod != null && Accessible(p.SetMethod); }
        if (!getOk && !setOk) return;
        string body = p.IsAbstract ? ";" : $" => throw new global::System.NotImplementedException(\"{FullName(p.ContainingType)}.{p.Name}\");";
        string getBody = body, setBody = body;
        if (!p.IsAbstract && IsNoop(p.ContainingType) && !p.ReturnsByRef) { getBody = " => default;"; setBody = " { }"; }
        sb.AppendLine($"{MI}{Acc(p)} {Mods(p)}{rt} {nm} {{ {(getOk ? Acc2(p.GetMethod) + "get" + getBody + " " : "")}{(setOk && !p.ReturnsByRef ? Acc2(p.SetMethod) + "set" + setBody + " " : "")}}}");
    }

    static readonly Dictionary<string, string> Ops = new()
    {
        ["op_Addition"] = "+", ["op_Subtraction"] = "-", ["op_Multiply"] = "*", ["op_Division"] = "/", ["op_Modulus"] = "%",
        ["op_Equality"] = "==", ["op_Inequality"] = "!=", ["op_LessThan"] = "<", ["op_GreaterThan"] = ">", ["op_LessThanOrEqual"] = "<=",
        ["op_GreaterThanOrEqual"] = ">=", ["op_UnaryNegation"] = "-", ["op_UnaryPlus"] = "+", ["op_LogicalNot"] = "!", ["op_True"] = "true",
        ["op_False"] = "false", ["op_BitwiseAnd"] = "&", ["op_BitwiseOr"] = "|", ["op_ExclusiveOr"] = "^", ["op_OnesComplement"] = "~",
        ["op_LeftShift"] = "<<", ["op_RightShift"] = ">>", ["op_Increment"] = "++", ["op_Decrement"] = "--",
    };

    static void EmitMethod(StringBuilder sb, string MI, IMethodSymbol m, bool isIface, INamedTypeSymbol explicitOf)
    {
        string tps = m.TypeParameters.Length > 0 ? "<" + string.Join(", ", m.TypeParameters.Select(p => p.Name)) + ">" : "";
        string ps = Params(m.Parameters);
        if (isIface) { sb.AppendLine($"{MI}{RetT(m)} {Esc(m.Name)}{tps}({ps}){Constraints(m.TypeParameters)};"); return; }
        if (explicitOf != null) { sb.AppendLine($"{MI}{RetT(m)} {T(explicitOf)}.{Esc(m.Name)}{tps}({ps}) => throw null;"); return; }
        if (m.MethodKind == MethodKind.UserDefinedOperator)
        {
            if (!Ops.TryGetValue(m.Name, out var op)) return;
            sb.AppendLine($"{MI}public static {RetT(m)} operator {op}({ps}) => throw null;");
            return;
        }
        if (m.MethodKind == MethodKind.Conversion)
        {
            sb.AppendLine($"{MI}public static {(m.Name == "op_Implicit" ? "implicit" : "explicit")} operator {T(m.ReturnType)}({ps}) => throw null;");
            return;
        }
        string mods = Mods(m);
        bool ovr = mods.Contains("override");
        string body = m.IsAbstract ? ";" : $" => throw new global::System.NotImplementedException(\"{FullName(m.ContainingType)}.{m.Name}\");";
        if (!m.IsAbstract && IsNoop(m.ContainingType))
        {
            var outs = string.Concat(m.Parameters.Where(x => x.RefKind == RefKind.Out).Select(x => $"{Esc(x.Name)} = default; "));
            body = m.ReturnsVoid ? $" {{ {outs}}}" : (m.ReturnsByRef || m.ReturnsByRefReadonly ? body : $" {{ {outs}return default; }}");
        }
        string ext = m.IsExtensionMethod ? "this " : "";
        sb.AppendLine($"{MI}{Acc(m)} {mods}{RetT(m)} {Esc(m.Name)}{tps}({ext}{ps}){(ovr ? OverrideConstraints(m.TypeParameters) : Constraints(m.TypeParameters))}{body}");
    }

    static string RetT(IMethodSymbol m) => (m.ReturnsByRef ? "ref " : m.ReturnsByRefReadonly ? "ref readonly " : "") + (m.ReturnsVoid ? "void" : T(m.ReturnType));

    static string Params(IEnumerable<IParameterSymbol> ps) => string.Join(", ", ps.Select(p =>
    {
        string pre = p.IsParams ? "params " : p.RefKind switch { RefKind.Ref => "ref ", RefKind.Out => "out ", RefKind.In => "in ", _ => "" };
        string def = p.HasExplicitDefaultValue ? " = " + Lit(p.ExplicitDefaultValue, p.Type) : "";
        return $"{pre}{T(p.Type)} {Esc(p.Name)}{def}";
    }));

    static string Esc(string n) => SyntaxFacts.GetKeywordKind(n) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(n) == SyntaxKind.None && false ? "@" + n : n;

    static string Constraints(IEnumerable<ITypeParameterSymbol> tps)
    {
        var sb = new StringBuilder();
        foreach (var tp in tps)
        {
            var c = new List<string>();
            if (tp.HasReferenceTypeConstraint) c.Add("class");
            if (tp.HasUnmanagedTypeConstraint) c.Add("unmanaged");
            else if (tp.HasValueTypeConstraint) c.Add("struct");
            foreach (var ct in tp.ConstraintTypes) if (TypeOk(ct)) c.Add(T(ct));
            if (tp.HasConstructorConstraint && !tp.HasValueTypeConstraint) c.Add("new()");
            if (c.Count > 0) sb.Append($" where {tp.Name} : {string.Join(", ", c)}");
        }
        return sb.ToString();
    }
    static string OverrideConstraints(IEnumerable<ITypeParameterSymbol> tps)
    {
        var sb = new StringBuilder();
        foreach (var tp in tps)
        {
            if (tp.HasReferenceTypeConstraint) sb.Append($" where {tp.Name} : class");
            else if (tp.HasValueTypeConstraint) sb.Append($" where {tp.Name} : struct");
        }
        return sb.ToString();
    }

    static string Lit(object v, ITypeSymbol t)
    {
        if (t.TypeKind == TypeKind.Enum && v != null) return $"({T(t)})({Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)})";
        if (v == null) return t is ITypeParameterSymbol ? "default" : t.IsValueType && t.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T ? "default" : "null";
        switch (v)
        {
            case float f:
                if (float.IsNaN(f)) return "float.NaN";
                if (float.IsPositiveInfinity(f)) return "float.PositiveInfinity";
                if (float.IsNegativeInfinity(f)) return "float.NegativeInfinity";
                if (f == float.MaxValue) return "float.MaxValue"; if (f == float.MinValue) return "float.MinValue";
                return f.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f";
            case double d:
                if (double.IsNaN(d)) return "double.NaN";
                if (double.IsPositiveInfinity(d)) return "double.PositiveInfinity";
                if (double.IsNegativeInfinity(d)) return "double.NegativeInfinity";
                if (d == double.MaxValue) return "double.MaxValue"; if (d == double.MinValue) return "double.MinValue";
                return d.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d";
            case bool b: return b ? "true" : "false";
            case string s: return SymbolDisplay.FormatLiteral(s, true);
            case char c: return SymbolDisplay.FormatLiteral(c, true);
            case long l: return l == long.MinValue ? "long.MinValue" : l + "L";
            case ulong ul: return ul + "UL";
            case uint ui: return ui + "U";
            case int i: return i == int.MinValue ? "int.MinValue" : i.ToString();
            default: return $"({T(t)})({Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture)})";
        }
    }
